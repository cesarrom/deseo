'use client';

import { useArticles } from '@deseo/api-client';
import { Card, CardContent, CardHeader, CardTitle, CardDescription } from '@deseo/ui/card';
import { Table, TableBody, TableCell, TableHead, TableHeader, TableRow } from '@deseo/ui/table';
import { Badge } from '@deseo/ui/badge';
import { Button } from '@deseo/ui/button';
import { Loader2, ExternalLink, Eye } from 'lucide-react';

const statusMap = {
  draft: { label: 'Draft', class: 'bg-slate-100 text-slate-700' },
  pending_review: { label: 'In Review', class: 'bg-yellow-100 text-yellow-700' },
  approved: { label: 'Approved', class: 'bg-blue-100 text-blue-700' },
  published: { label: 'Published', class: 'bg-green-100 text-green-700' },
  archived: { label: 'Archived', class: 'bg-red-100 text-red-700' },
};

export default function ArticlesPage() {
  const { data: articles, isLoading } = useArticles();

  if (isLoading) {
    return (
      <div className="flex h-[60vh] items-center justify-center">
        <Loader2 className="h-8 w-8 animate-spin text-blue-600" />
      </div>
    );
  }

  return (
    <div className="space-y-8">
      <div className="flex items-center justify-between">
        <div>
          <h1 className="text-3xl font-bold tracking-tight text-slate-900">Articles</h1>
          <p className="text-slate-500">Manage your generated content and publishing pipeline.</p>
        </div>
        <Button onClick={() => window.location.href='/dashboard/intelligence'}>
          Generate New Article
        </Button>
      </div>

      <Card>
        <CardHeader>
          <CardTitle>Recent Articles</CardTitle>
          <CardDescription>A list of all articles generated by Deseo.</CardDescription>
        </CardHeader>
        <CardContent>
          <Table>
            <TableHeader>
              <TableRow>
                <TableHead>Title</TableHead>
                <TableHead>Status</TableHead>
                <TableHead>Target CMS</TableHead>
                <TableHead>Created</TableHead>
                <TableHead className="text-right">Actions</TableHead>
              </TableRow>
            </TableHeader>
            <TableBody>
              {articles?.map((article) => {
                const status = statusMap[article.status as keyof typeof statusMap];
                return (
                  <TableRow key={article.id}>
                    <TableCell className="font-medium">
                      <div className="flex flex-col">
                        <span>{article.title}</span>
                        <span className="text-xs text-slate-400 font-normal">/{article.slug}</span>
                      </div>
                    </TableCell>
                    <TableCell>
                      <Badge className={status.class}>
                        {status.label}
                      </Badge>
                    </TableCell>
                    <TableCell>
                      <span className="capitalize">{article.targetCms || 'None'}</span>
                    </TableCell>
                    <TableCell className="text-slate-500 text-sm">
                      {new Date(article.createdAt).toLocaleDateString()}
                    </TableCell>
                    <TableCell className="text-right">
                      <div className="flex justify-end gap-2">
                        <Button size="icon" variant="ghost" className="h-8 w-8">
                          <Eye className="h-4 w-4" />
                        </Button>
                        {article.cmsPublishedId && (
                          <Button size="icon" variant="ghost" className="h-8 w-8 text-blue-600">
                            <ExternalLink className="h-4 w-4" />
                          </Button>
                        )}
                      </div>
                    </TableCell>
                  </TableRow>
                );
              })}

              {(!articles || articles.length === 0) && (
                <TableRow>
                  <TableCell colSpan={5} className="h-32 text-center text-slate-500">
                    No articles found. Go to Intelligence to generate your first piece.
                  </TableCell>
                </TableRow>
              )}
            </TableBody>
          </Table>
        </CardContent>
      </Card>
    </div>
  );
}
